        public void Export(Scene scene, Stream stream, SaveOptions options)
        {
            if (options is FbxSaveOptions fbxOptions)
            {
                if (fbxOptions.IsAscii)
                {
                    WriteAsciiFbx(stream, scene);
                }
                else
                {
                    WriteBinaryFbx(stream, scene);
                }
            }
            else
            {
                throw new ArgumentException("Options must be FbxSaveOptions", nameof(options));
            }
        }

        private static void WriteBinaryFbx(Stream stream, Scene scene)
        {
            using var writer = new BinaryWriter(stream, Encoding.ASCII, leaveOpen: true);

            WriteHeader(writer);
            WriteGlobalInfo(writer);
            WriteObjects(writer, scene);
            WriteConnections(writer, scene);
            WriteFooter(writer);
        }

        private static void WriteAsciiFbx(Stream stream, Scene scene)
        {
            using var writer = new StreamWriter(stream, new UTF8Encoding(false), leaveOpen: true);

            WriteAsciiHeader(writer);
            WriteAsciiGlobalSettings(writer, scene);
            WriteAsciiDocuments(writer);
            WriteAsciiDefinitions(writer, scene);
            WriteAsciiObjects(writer, scene);
            WriteAsciiConnections(writer, scene);
            WriteAsciiTakes(writer);
        }

