        private static void WriteAsciiObjects(StreamWriter writer, Scene scene)
        {
            writer.WriteLine("; Object properties");
            writer.WriteLine(";------------------------------------------------------------------");
            writer.WriteLine();
            writer.WriteLine("Objects:  {");
            
            var meshId = 22123456;
            var materialId = 22129008;
            var nodeId = 22115008;
            
            var meshToId = new Dictionary<Mesh, int>();
            var materialToId = new Dictionary<Material, int>();
            var nodeToId = new Dictionary<Node, int>();
            
            var materials = new HashSet<Material>();
            var meshes = new HashSet<Mesh>();
            CollectMaterials(scene.RootNode, materials);
            CollectMeshes(scene.RootNode, meshes);
            
            foreach (var material in materials)
            {
                materialToId[material] = materialId++;
            }
            
            foreach (var mesh in meshes)
            {
                meshToId[mesh] = meshId++;
            }
            
            WriteNodes(writer, scene, scene.RootNode, nodeToId, ref nodeId, meshToId, materialToId, 0);
            
            writer.WriteLine("}");
        }

