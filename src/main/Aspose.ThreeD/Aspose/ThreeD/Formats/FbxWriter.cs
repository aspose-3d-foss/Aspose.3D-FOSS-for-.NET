        private static void WriteAsciiConnectionsRecursive(StreamWriter writer, Node node, Dictionary<Node, int> nodeToId, Dictionary<Mesh, int> meshToId, Dictionary<Material, int> materialToId)
        {
            foreach (var childNode in node.ChildNodes)
            {
                writer.WriteLine($"\tC: \"OO\",{nodeToId[childNode]},{nodeToId[node]}");
            }

            foreach (var entity in node.Entities)
            {
                if (entity is Mesh mesh)
                {
                    if (meshToId.TryGetValue(mesh, out int meshId))
                    {
                        writer.WriteLine($"\tC: \"OO\",{meshId},{nodeToId[node]}");
                    }
                }
                else if (entity is Primitive primitive)
                {
                    var primMesh = primitive.ToMesh();
                    if (meshToId.TryGetValue(primMesh, out int primMeshId))
                    {
                        writer.WriteLine($"\tC: \"OO\",{primMeshId},{nodeToId[node]}");
                    }
                }
            }

            foreach (var material in node.Materials)
            {
                if (materialToId.TryGetValue(material, out int matId))
                {
                    writer.WriteLine($"\tC: \"OO\",{matId},{nodeToId[node]}");
                }
            }

            foreach (var childNode in node.ChildNodes)
            {
                WriteAsciiConnectionsRecursive(writer, childNode, nodeToId, meshToId, materialToId);
            }
        }

